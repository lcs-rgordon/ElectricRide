CREATE OR REPLACE VIEW "public"."listings_with_details" WITH ("security_invoker"='on') AS
 SELECT "l"."id",
    "l"."price",
    "l"."description",
    "l"."listed_on",
    "mk"."brand_name" AS "brand",
    "mdl"."name" AS "model",
    "y"."name" AS "year",
    "c"."name" AS "colour",
    "d"."description" AS "drivetrain"
   FROM (((((("public"."listing" "l"
     JOIN "public"."vehicle" "v" ON (("l"."vehicle_id" = "v"."id")))
     JOIN "public"."make" "mk" ON (("v"."make_id" = "mk"."id")))
     JOIN "public"."model" "mdl" ON (("v"."model_id" = "mdl"."id")))
     JOIN "public"."year" "y" ON (("v"."year_id" = "y"."id")))
     JOIN "public"."colour" "c" ON (("v"."colour_id" = "c"."id")))
     JOIN "public"."drivetrain" "d" ON (("v"."drivetrain_id" = "d"."id")))
  WHERE ("l"."is_active" = true);


