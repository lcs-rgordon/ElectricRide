CREATE OR REPLACE VIEW "public"."count_of_vehicles_by_brand" AS
 SELECT "mk"."brand_name" AS "brand",
    "count"("l"."id") AS "vehicles_available"
   FROM (("public"."listing" "l"
     JOIN "public"."vehicle" "v" ON (("l"."vehicle_id" = "v"."id")))
     JOIN "public"."make" "mk" ON (("v"."make_id" = "mk"."id")))
  WHERE ("l"."is_active" = true)
  GROUP BY "mk"."brand_name";


